// ─── QUERY HELPER FUNCTIONS ───
export const getProductBySlug = (slug) => products.find(p => p.slug === slug);
export const getProductById = (id) => products.find(p => p.id === Number(id));
export const getProductsByCategory = (category) => products.filter(p => p.category === category);
export const getProductsBySubcategory = (subcategory) => products.filter(p => p.subcategory === subcategory);
export const getFeaturedProducts = () => products.filter(p => p.isFeatured);
export const getBestSellers = () => products.filter(p => p.isBestSeller);
export const getNewArrivals = () => products.filter(p => p.isNew);
export const getTrendingProducts = () => products.filter(p => p.isTrending);
export const getWeddingProducts = () => products.filter(p => p.isWeddingSpecial);
export const getFestivalProducts = () => products.filter(p => p.isFestivalSpecial);
export const getHandmadeProducts = () => products.filter(p => p.isHandmade);

export const searchProducts = (query) => {
  if (!query) return products;
  const q = query.toLowerCase().trim();
  return products.filter(p => 
    p.name.toLowerCase().includes(q) ||
    p.category.toLowerCase().includes(q) ||
    p.subcategory.toLowerCase().includes(q) ||
    p.shortDescription?.toLowerCase().includes(q) ||
    p.material?.toLowerCase().includes(q) ||
    p.color?.toLowerCase().includes(q)
  );
};

export const getRelatedProducts = (product, limit = 4) => {
  if (!product) return [];
  return products
    .filter(p => p.id !== product.id && (p.category === product.category || p.subcategory === product.subcategory))
    .slice(0, limit);
};
